"""Connessione al database Postgres (Supabase) e schema delle tabelle.

Sicurezza su Supabase:
- tutte le tabelle hanno RLS attivo e nessuna policy per i ruoli `anon`/`authenticated`:
  la Data API pubblica di Supabase non può leggerle né scriverle;
- l'app si collega con il ruolo `postgres` (che ignora RLS) per utenti, crediti e pagamenti;
- le candidature si leggono e scrivono invece con il ruolo APP_ROLE, soggetto alla policy
  `user_id = app.current_user_id`: anche una query sbagliata non vede i dati di altri utenti.
"""

import atexit
import threading
from contextlib import contextmanager
from typing import Iterator

import psycopg
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

import config

APP_ROLE = "cv_app_user"

_SCHEMA = f"""
SELECT pg_advisory_xact_lock(4207);  -- due avvii in contemporanea non creano lo schema due volte

CREATE TABLE IF NOT EXISTS users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 TEXT        NOT NULL UNIQUE,
    password_hash         TEXT        NOT NULL,
    credits               INTEGER     NOT NULL DEFAULT 0 CHECK (credits >= 0),
    is_admin              BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    recovery_hash         TEXT,  -- vecchio codice di recupero, sostituito dal reset via email
    -- «Le mie candidature», attivata per singolo utente dal pannello admin.
    can_save_applications BOOLEAN     NOT NULL DEFAULT FALSE
);
-- Email confermata con il codice inviato alla registrazione. Gli account creati prima
-- della conferma email valgono come confermati (DEFAULT TRUE quando la colonna nasce),
-- i nuovi partono non confermati.
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE users ALTER COLUMN email_verified SET DEFAULT FALSE;
-- Accettazione di Termini e Informativa privacy alla registrazione (versione = data dei testi).
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_version TEXT;
-- Nome e cognome, chiesti alla registrazione (gli account precedenti li inseriscono al primo acquisto).
ALTER TABLE users ADD COLUMN IF NOT EXISTS first_name TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_name TEXT;
-- Cliente Stripe dell'utente, con nome ed email: uno per modalità, perché test e live sono separati.
ALTER TABLE users ADD COLUMN IF NOT EXISTS stripe_customer_test TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS stripe_customer_live TEXT;

-- Codici a 6 cifre inviati per email (conferma dell'indirizzo, reset della password): uno per scopo.
CREATE TABLE IF NOT EXISTS email_codes (
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose    TEXT        NOT NULL CHECK (purpose IN ('verify', 'reset')),
    code_hash  TEXT        NOT NULL,
    attempts   INTEGER     NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, purpose)
);

-- Acquisti già erogati: la chiave sulla sessione Stripe rende l'erogazione idempotente.
CREATE TABLE IF NOT EXISTS payments (
    stripe_session_id TEXT        PRIMARY KEY,
    -- NULL se l'account è stato eliminato: l'acquisto resta nelle vendite.
    user_id           BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    credits           INTEGER     NOT NULL,
    amount_total      INTEGER     NOT NULL,
    currency          TEXT        NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS payments_user_idx ON payments (user_id);
-- Pagamento vero (chiavi live) o di prova (chiavi test). I pagamenti registrati prima di
-- questa colonna erano tutti di prova.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS livemode BOOLEAN NOT NULL DEFAULT FALSE;

-- Accessi ricordati dal browser (cookie): si salva solo l'hash del token.
CREATE TABLE IF NOT EXISTS login_sessions (
    token_hash TEXT        PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);

-- Impostazioni modificabili dal pannello admin (valori '0'/'1' per i flag).
CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- Un record per ogni operazione con Claude andata a buon fine (anche degli admin).
CREATE TABLE IF NOT EXISTS usage_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL se l'account è stato eliminato: l'operazione resta nelle statistiche.
    user_id    BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    action     TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS usage_log_user_idx ON usage_log (user_id);

-- Database creati prima dell'eliminazione degli account: pagamenti e statistiche passano a SET NULL.
DO $$
DECLARE
    fk TEXT;
BEGIN
    FOREACH fk IN ARRAY ARRAY['payments', 'usage_log'] LOOP
        IF EXISTS (SELECT FROM pg_constraint WHERE conname = fk || '_user_id_fkey' AND confdeltype <> 'n') THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN user_id DROP NOT NULL', fk);
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', fk, fk || '_user_id_fkey');
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (user_id) '
                           'REFERENCES users(id) ON DELETE SET NULL', fk, fk || '_user_id_fkey');
        END IF;
    END LOOP;
END $$;

CREATE TABLE IF NOT EXISTS saved_applications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    company_name  TEXT        NOT NULL,
    job_title     TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    cv_json       JSONB       NOT NULL,
    cover_letter  TEXT        NOT NULL,
    linkedin_json JSONB,
    match_score   INTEGER,
    -- Per riaprire la candidatura nel percorso guidato.
    base_cv_json  JSONB,
    job_text      TEXT,
    match_json    JSONB
);
CREATE INDEX IF NOT EXISTS saved_applications_user_idx ON saved_applications (user_id, created_at DESC);
-- Salvataggio automatico: anche bozze non ancora pagate (solo CV, o senza consegna). Quelle salvate a mano
-- prima di questa colonna erano già pagate.
ALTER TABLE saved_applications ADD COLUMN IF NOT EXISTS paid BOOLEAN NOT NULL DEFAULT TRUE;

-- Crediti per lotto (acquisto, regalo dell'admin, crediti iniziali): ogni lotto scade dopo
-- CREDITS_VALIDITY_MONTHS mesi e si consumano prima i lotti che scadono prima.
-- users.credits resta il saldo, cioè la somma di credits_left dei lotti.
CREATE TABLE IF NOT EXISTS credit_lots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source            TEXT        NOT NULL CHECK (source IN ('purchase', 'admin', 'initial', 'legacy')),
    stripe_session_id TEXT,
    credits           INTEGER     NOT NULL CHECK (credits > 0),
    credits_left      INTEGER     NOT NULL CHECK (credits_left >= 0),
    expired_credits   INTEGER     NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at        TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS credit_lots_open_idx ON credit_lots (user_id, expires_at) WHERE credits_left > 0;

-- Saldi non coperti da lotti (account precedenti alla scadenza dei crediti): la differenza
-- diventa un lotto che scade tra CREDITS_VALIDITY_MONTHS mesi da oggi.
INSERT INTO credit_lots (user_id, source, credits, credits_left, expires_at)
SELECT u.id, 'legacy', u.credits - COALESCE(l.n, 0), u.credits - COALESCE(l.n, 0),
       now() + make_interval(months => {config.CREDITS_VALIDITY_MONTHS})
FROM users u
LEFT JOIN (SELECT user_id, SUM(credits_left) AS n FROM credit_lots GROUP BY user_id) l ON l.user_id = u.id
WHERE u.credits > COALESCE(l.n, 0);

ALTER TABLE users              ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments           ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_sessions     ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings           ENABLE ROW LEVEL SECURITY;
ALTER TABLE usage_log          ENABLE ROW LEVEL SECURITY;
ALTER TABLE saved_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE email_codes        ENABLE ROW LEVEL SECURITY;
ALTER TABLE credit_lots        ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN
        CREATE ROLE {APP_ROLE} NOLOGIN NOINHERIT NOBYPASSRLS;
    END IF;
END $$;
-- Serve per SET ROLE: l'utente di connessione deve poter assumere il ruolo applicativo.
GRANT {APP_ROLE} TO CURRENT_USER;
GRANT USAGE ON SCHEMA public TO {APP_ROLE};
GRANT SELECT, INSERT, UPDATE, DELETE ON saved_applications TO {APP_ROLE};

DROP POLICY IF EXISTS own_applications ON saved_applications;
CREATE POLICY own_applications ON saved_applications FOR ALL TO {APP_ROLE}
    USING (user_id = nullif(current_setting('app.current_user_id', true), '')::bigint)
    WITH CHECK (user_id = nullif(current_setting('app.current_user_id', true), '')::bigint);
"""

_pool: ConnectionPool | None = None
_schema_ready = False
_lock = threading.Lock()
_schema_lock = threading.Lock()


def _get_pool() -> ConnectionPool:
    global _pool
    with _lock:
        if _pool is None:
            if not config.DATABASE_URL:
                raise RuntimeError("DATABASE_URL mancante: impostala nel file .env (stringa di connessione Supabase).")
            _pool = ConnectionPool(
                config.DATABASE_URL,
                min_size=1,
                max_size=config.DB_POOL_MAX_SIZE,
                # prepare_threshold=None: compatibile anche con il pooler Supabase in «transaction mode».
                kwargs={"row_factory": dict_row, "prepare_threshold": None},
                # Supabase chiude le connessioni inattive: si verificano prima di riusarle.
                check=ConnectionPool.check_connection,
                name="cv-architect",
                open=True,
            )
            # Senza chiusura esplicita gli script (es. manage_users.py) attendono i thread del pool all'uscita.
            atexit.register(_pool.close)
    return _pool


@contextmanager
def transaction() -> Iterator[psycopg.Connection]:
    """Connessione dal pool: commit all'uscita, rollback se il blocco solleva un'eccezione."""
    ensure_schema()
    with _get_pool().connection() as conn:
        yield conn


@contextmanager
def user_scoped_transaction(user_id: int) -> Iterator[psycopg.Connection]:
    """Transazione con il ruolo applicativo e l'utente collegato: le policy RLS filtrano le righe."""
    with transaction() as conn:
        conn.execute(f"SET LOCAL ROLE {APP_ROLE}")
        conn.execute("SELECT set_config('app.current_user_id', %s, true)", (str(int(user_id)),))
        yield conn


def ensure_schema() -> None:
    """Crea o aggiorna lo schema una volta per processo."""
    global _schema_ready
    if _schema_ready:
        return
    with _schema_lock:
        if _schema_ready:
            return
        with _get_pool().connection() as conn:
            conn.execute(_SCHEMA)
            if config.ADMIN_EMAILS:
                conn.execute("UPDATE users SET is_admin = TRUE WHERE email = ANY(%s)", (config.ADMIN_EMAILS,))
        _schema_ready = True
